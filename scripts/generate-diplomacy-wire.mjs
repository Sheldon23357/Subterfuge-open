import {readFileSync,writeFileSync} from 'node:fs';
const source='packages/rules/src/diplomacy.ts',target='packages/contracts/src/diplomacy.generated.ts';
const code=readFileSync(source,'utf8');
if(/\bimport\s|\bfrom\s+['"]/.test(code))throw Error('Diplomacy wire source must remain platform- and dependency-free');
const expected='// Generated by scripts/generate-diplomacy-wire.mjs from '+source+'. Do not edit.\n'+code;
if(process.argv.slice(2).join() === '--check'){
 if(readFileSync(target,'utf8').replaceAll('\r\n','\n')!==expected.replaceAll('\r\n','\n'))throw Error('Diplomacy wire is stale; run node scripts/generate-diplomacy-wire.mjs');
}else if(process.argv.length===2)writeFileSync(target,expected);else throw Error('Usage: node scripts/generate-diplomacy-wire.mjs [--check]');
